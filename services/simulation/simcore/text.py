"""Форматирование чисел и склонений для текстов, которые читает пользователь.

Доли, склонение числительных и готовые обороты «19 роботов», «на 5
станциях» — единственный потребитель этого модуля тексты вердикта.
"""

from __future__ import annotations


def num(x: float, d: int = 1) -> str:
    """Возвращает число с запятой как десятичным разделителем."""
    return f"{x:.{d}f}".replace(".", ",")


def pp(x: float) -> str:
    """Возвращает долю как проценты: 0.95 → «95,0 %»."""
    return num(x * 100) + " %"


def plural(n: int, one: str, few: str, many: str) -> str:
    """Выбирает форму существительного по числу.

    Args:
        n: число, к которому относится существительное.
        one: форма для 1 («робот»).
        few: форма для 2–4 («робота»).
        many: форма для 5 и больше («роботов»).

    Returns:
        Подходящую форму слова.
    """
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def robots(n: int) -> str:
    """Возвращает «19 роботов» — число с просклонённым существительным."""
    word = plural(n, "робот", "робота", "роботов")
    return f"{n} {word}"


def chargers(n: int) -> str:
    """Возвращает «5 зарядных станций»."""
    word = plural(n, "зарядная станция", "зарядные станции", "зарядных станций")
    return f"{n} {word}"


def stations(n: int) -> str:
    """Возвращает «5 станций» — короткая форма для текстов подбора."""
    return f"{n} {plural(n, "станция", "станции", "станций")}"


def at_robots(n: int) -> str:
    """Возвращает «на 19 роботах» — предложный падеж."""
    return f"{n} {plural(n, "роботе", "роботах", "роботах")}"


def at_stations(n: int) -> str:
    """Возвращает «на 5 станциях» — предложный падеж."""
    return f"{n} {plural(n, "станции", "станциях", "станциях")}"
